// Связка «ключевые фразы → тег». 
// Ключи — как пользователь может написать (в нижнем регистре).
// Значения — тег, который должен быть в product.tags.
export const QUERY_TO_TAGS: Record<string, string[]> = {
  // Новый год
  "новый год": ["новый год", "новогодний", "зима"],
  "новогод": ["новый год", "новогодний"],
  "с новым годом": ["новый год", "новогодний"],
  "зима": ["зима", "новогодний"],
  "снег": ["зима", "новогодний"],

  // День рождения
  "день рождения": ["день рождения"],
  "днюх": ["день рождения"],
  "др": ["день рождения"],

  // 8 марта
  "8 марта": ["8 марта"],
  "8-мар": ["8 марта"],
  "женский день": ["8 марта"],

  // Учитель
  "учитель": ["учитель", "благодарность"],
  "учителю": ["учитель"],
  "педагог": ["учитель"],
  "благодарность": ["благодарность"],

  // Лето
  "лето": ["лето"],
  "летний": ["лето"],
  "фрукты": ["лето", "фрукты"],
  "цветы": ["цветы"],

  // Мама
  "мама": ["мама"],
  "маме": ["мама"],
  "мамочке": ["мама"],

  // Пожелания / универсальные
  "пожелания": ["пожелания"],
  "подарок": ["подарок"],
  "мини": ["мини"],
};

/**
 * Возвращает теги, соответствующие запросу.
 * Если запрос не похож ни на одну ключевую фразу — пустой массив.
 */
export function tagsForQuery(rawQuery: string): string[] {
  const q = rawQuery.toLowerCase().trim().replace(/\s+/g, " ");
  if (!q) return [];

  const result = new Set<string>();

  for (const [phrase, tags] of Object.entries(QUERY_TO_TAGS)) {
    // совпадение, если запрос содержит фразу целиком
    // либо фраза содержит запрос (для коротких вроде «учит»)
    if (q.includes(phrase) || phrase.includes(q)) {
      tags.forEach((t) => result.add(t));
    }
  }

  return [...result];
}